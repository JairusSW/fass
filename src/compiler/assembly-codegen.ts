import { openSchema } from "../runtime/schema.js";
import { verifySchema } from "../runtime/verify.js";
import { TypeView } from "../runtime/reflection.js";
import { NO_INDEX as N, Kind, width } from "../format.js";
/** Emit borrowed Wasm pointer views from the same authoritative compiled image. */
export function generateAssemblyscript(bytes: Uint8Array): string {
  const s = openSchema(bytes);
  verifySchema(s);
  const out = [
    `// Generated by fass. Keep schema and backing bytes alive and immutable while views are retained.`,
    `import {Code,Schema,RecordView,ValueView,MapView,readWord,sumU32x4Unchecked,sumU32Unchecked} from 'fass/assembly';`,
    `export const schemaBytes:StaticArray<u8>=[${[...bytes].join(",")}];`,
    `export const schema=new Schema();schema.open(changetype<usize>(schemaBytes),${bytes.length});`,
    `@inline function fits(length:u32,offset:u64,size:u64):bool{return offset<=length&&size<=<u64>length-offset;}`,
    `@inline function addressable(data:usize,length:u32):bool{return <u64>data+length<=<u64>memory.size()*65536;}`,
    `export class Span {data:usize=0;length:u32=0;offset:u32=0;count:u32=0;status:Code=Code.Malformed;}`,
    `@inline function span(data:usize,length:u32,at:u32,d:u32,o:u32,l:u32,limit:u32,stride:u32,packed:bool,out:Span):Code {if(!fits(length,at,d))return out.status=Code.Malformed;const n=readWord(data+at,d);if(o+l<64&&n>>(o+l))return out.status=Code.Malformed;const offset=<u32>(n&((<u64>1<<o)-1)),count=<u32>(n>>o);if(count>limit)return out.status=Code.BoundExceeded;const size=packed?(<u64>count+7)/8:<u64>count*stride;if((!size&&offset)||(size&&!offset)||!fits(length,offset,size))return out.status=Code.Malformed;out.data=data;out.length=length;out.offset=offset;out.count=count;return out.status=Code.Ok;}`,
    `@inline function string24(data:usize,length:u32,at:u32,limit:u32,out:Span):Code {const word=load<u32>(data+at),offset=word&0xffffff,count=word>>>24;if(limit<255&&count>limit)return out.status=Code.BoundExceeded;if((count==0)!=(offset==0)||count>length||offset>length-count)return out.status=Code.Malformed;out.data=data;out.length=length;out.offset=offset;out.count=count;return out.status=Code.Ok;}`,
  ];
  const types = [
    "",
    "i8",
    "u8",
    "i16",
    "u16",
    "i32",
    "u32",
    "i64",
    "u64",
    "f32",
    "f64",
    "bool",
  ];
  const read = (k: number, at: string, bit = 0) =>
    k === 11 ? `(load<u8>(${at})&${1 << bit})!=0` : `load<${types[k]}>(${at})`;
  const desc = (p: number, at: string, to: string) =>
    s.u8(p) === 12 &&
    s.u8(p + 1) === 4 &&
    s.u8(p + 2) === 24 &&
    s.u8(p + 3) === 8
      ? `string24(this.data,this.length,${at},${s.u32(p + 16)},${to})`
      : `span(this.data,this.length,${at},${s.u8(p + 1)},${s.u8(p + 2)},${s.u8(p + 3)},${s.u32(p + 16)},${s.u8(p) === 12 ? 1 : s.u32(p + 12)},${!!(s.u32(p + 4) & 1)},${to})`;
  const base = `data:usize=0;length:u32=0;anchor:u32=0;status:Code=Code.Malformed;writable:bool=false;readOnly:bool=false;`;
  for (let li = 0; li < s.count(1); li++) {
    const l = s.layout(li),
      first = s.u32(l + 4),
      td = new TypeView(s, s.u32(l + 12));
    out.push(
      `export class Layout${li} {${base}private value:ValueView=new ValueView(schema);private record:RecordView=new RecordView(schema);`,
    );
    out.push(
      `_bind(data:usize,length:u32,anchor:u32,writable:bool,readOnly:bool):Code{this.data=data;this.length=length;this.anchor=anchor;this.writable=writable;this.readOnly=readOnly;return this.status=Code.Ok;}`,
    );
    if (li === s.root)
      out.push(
        `open(data:usize,length:u32,writable:bool=false):Code{if(!addressable(data,length)||length>${s.maxBytes}||length<${s.u32(l)})return this.status=Code.Malformed;return this._bind(data,length,0,writable,false);}`,
      );
    for (let slot = 0; slot < s.u32(l + 8); slot++) {
      const fi = first + slot,
        a = s.access(fi),
        link = s.entry(3, fi),
        k = s.u8(a + 4),
        flags = s.u8(a + 5),
        target = s.u32(link),
        presence = s.u32(link + 4),
        name = td.field(slot).name(),
        method = "get" + name[0].toUpperCase() + name.slice(1),
        at = `this.anchor+${s.u32(a)}`;
      const guard =
        presence === N
          ? ""
          : (() => {
              const p = s.entry(6, presence);
              return `if(!(load<u8>(this.data+this.anchor+${s.u32(p)})&${s.u8(p + 4)})){this.status=Code.Absent;return ${k <= 11 ? "0" : "this.status"};}`;
            })();
      if (k <= 11) {
        out.push(
          `@inline ${method}():${types[k]}{if(this.status!=Code.Ok)return 0;${guard}return ${read(k, `this.data+${at}`, s.u8(a + 6))};}`,
        );
        if (!(flags & 2))
          out.push(
            `set${name[0].toUpperCase() + name.slice(1)}(value:${types[k]}):Code{if(this.status!=Code.Ok)return this.status;let c=this.record.bind(this.data,this.length,${li},this.anchor,this.writable,this.readOnly);if(c==Code.Ok)c=this.record.atSlot(${slot},this.value);if(c!=Code.Ok)return this.status=c;return this.status=${k === 11 ? "this.value.setBool(value)" : k >= 9 ? `this.value.setBits(${k === 9 ? "<u64>reinterpret<u32>(value)" : "reinterpret<u64>(value)"})` : `this.value.setBits(<u64><${["", "u8", "u8", "u16", "u16", "u32", "u32", "u64", "u64"][k] || types[k]}>value)`};}`,
          );
      } else if (k === 15 || k === 16) {
        const head = s.u32(s.layout(target));
        out.push(
          `@inline ${method}Into(out:Layout${target}):Code{if(this.status!=Code.Ok)return out.status=this.status;${guard}${k === 16 ? `const n=readWord(this.data+${at},${flags >> 4});if(n>=<u64>1<<${s.u8(a + 6)}||(${head}&&!n)||!fits(this.length,n,${head}))return out.status=Code.Malformed;` : ""}return out._bind(this.data,this.length,${k === 15 ? "this.anchor" : "<u32>n"},this.writable,this.readOnly||${!!(flags & 2)});}`,
        );
      } else if (k === 12)
        out.push(
          `@inline ${method}BytesInto(out:Span):Code{if(this.status!=Code.Ok)return out.status=this.status;${guard}return ${desc(s.plan(target), at, "out")};}`,
        );
      else if (k === 13 || k === 14) {
        const p = s.plan(target);
        out.push(
          `@inline ${method}Into(out:ArrayPlan${target}):Code{if(this.status!=Code.Ok)return out.status=this.status;${guard}${k === 13 ? `const c=${desc(p, at, "out")};if(c!=Code.Ok)return c;` : `out.data=this.data;out.length=this.length;out.offset=${at};out.count=${s.u32(p + 16)};out.status=Code.Ok;`}out.writable=this.writable;out.readOnly=this.readOnly||${!!(flags & 2)};return out.status;}`,
        );
      } else
        out.push(
          `@inline ${method}Into(out:MapView):Code{let c=this.record.bind(this.data,this.length,${li},this.anchor,this.writable,this.readOnly);if(c==Code.Ok)c=this.record.atSlot(${slot},this.value);return c==Code.Ok?out.bind(this.value):c;}`,
        );
    }
    const offsets: number[] = [];
    for (let slot = 0; slot < s.u32(l + 8); slot++) {
      const fi = first + slot,
        a = s.access(fi),
        link = s.entry(3, fi);
      if (s.u8(a + 4) === Kind.U32 && s.u32(link + 4) === N)
        offsets.push(s.u32(a));
      const ck = s.u8(a + 4);
      if (ck === 12 && s.u32(link + 4) === N) {
        const vp = s.plan(s.u32(link)),
          name = td.field(slot).name(),
          method = "get" + name[0].toUpperCase() + name.slice(1);
        if (s.u8(vp + 1) === 4 && s.u8(vp + 2) === 24 && s.u8(vp + 3) === 8)
          out.push(
            `/** Head extent must already be established. High word 0xffffffff reports a Code in the low word. */ @inline static ${method}SpanAt(head:usize,data:usize,length:u32):u64{const word=load<u32>(head+${s.u32(a)}),offset=word&0xffffff,count=word>>>24;${s.u32(vp + 16) < 255 ? `if(count>${s.u32(vp + 16)})return 0xffffffff00000004;` : ""}if((count==0)!=(offset==0)||count>length||offset>length-count)return 0xffffffff0000000a;return (<u64>count<<32)|<u64>(data+offset);}`,
          );
      }
    }
    offsets.sort((a, b) => a - b);
    if (offsets.length) {
      const terms: string[] = [];
      for (let i = 0; i < offsets.length;) {
        if (
          i + 3 < offsets.length &&
          offsets[i + 3] === offsets[i] + 12 &&
          offsets[i + 1] === offsets[i] + 4 &&
          offsets[i + 2] === offsets[i] + 8
        ) {
          terms.push(`sumU32x4Unchecked(head+${offsets[i]})`);
          i += 4;
        } else terms.push(`<u64>load<u32>(head+${offsets[i++]})`);
      }
      out.push(
        `/** Supply a head established by this exact generated layout. */ @inline static sumU32FieldsUnchecked(head:usize):u64{return ${terms.join("+")};}`,
      );
    }
    out.push("}");
  }
  for (let pi = 0; pi < s.count(4); pi++) {
    const p = s.plan(pi),
      pk = s.u8(p);
    if (pk !== 13 && pk !== 14) continue;
    const child = s.u32(p + 20),
      cp = s.plan(child),
      k = s.u8(cp),
      stride = s.u32(p + 12),
      packed = !!(s.u32(p + 4) & 1),
      at = packed ? "this.offset+index/8" : `this.offset+index*${stride}`,
      guard = `if(this.status!=Code.Ok)return ${k <= 11 ? "0" : "out.status=this.status"};if(index>=this.count){this.status=Code.BoundExceeded;return ${k <= 11 ? "0" : "out.status=this.status"};}`;
    out.push(
      `export class ArrayPlan${pi} extends Span {writable:bool=false;readOnly:bool=false;private value:ValueView=new ValueView(schema);`,
    );
    if (k === Kind.Record)
      out.push(
        `@inline atPointer(index:u32):usize{if(this.status!=Code.Ok)return 0;if(index>=this.count){this.status=Code.BoundExceeded;return 0;}return this.data+this.offset+index*${stride};}`,
      );
    if (k <= 11)
      out.push(
        `@inline get(index:u32):${types[k]}{${guard}return ${packed ? "(load<u8>(this.data+this.offset+index/8)&(1<<(index%8)))!=0" : read(k, `this.data+${at}`)};}`,
      );
    else if (k === 15 || k === 16) {
      const target = s.u32(cp + 20),
        head = s.u32(s.layout(target));
      out.push(
        `@inline atInto(index:u32,out:Layout${target}):Code{${guard}${k === 16 ? `const n=readWord(this.data+${at},${s.u8(cp + 1)});if(n>=<u64>1<<${s.u8(cp + 2)}||(${head}&&!n)||!fits(this.length,n,${head}))return out.status=Code.Malformed;` : ""}return out._bind(this.data,this.length,${k === 15 ? at : "<u32>n"},this.writable,this.readOnly);}`,
      );
    } else if (k === 12)
      out.push(
        `@inline bytesInto(index:u32,out:Span):Code{${guard}return ${desc(cp, at, "out")};}`,
      );
    else if (k === 13 || k === 14)
      out.push(
        `@inline atInto(index:u32,out:ArrayPlan${child}):Code{${guard}${k === 13 ? `const c=${desc(cp, at, "out")};if(c!=Code.Ok)return c;` : `out.data=this.data;out.length=this.length;out.offset=${at};out.count=${s.u32(cp + 16)};out.status=Code.Ok;`}out.writable=this.writable;out.readOnly=this.readOnly;return out.status;}`,
      );
    else
      out.push(
        `@inline atInto(index:u32,out:MapView):Code{${guard}const c=this.value.bindPlan(this.data,this.length,${child},${at},this.writable,this.readOnly);return c==Code.Ok?out.bind(this.value):c;}`,
      );

    if (k === Kind.U32)
      out.push(
        `sum():u64{if(this.status!=Code.Ok)return 0;return sumU32Unchecked(this.data+this.offset,this.count);}`,
      );
    if (k === Kind.Record) {
      const li = s.u32(cp + 20),
        l = s.layout(li),
        offsets: number[] = [];
      for (let slot = 0; slot < s.u32(l + 8); slot++) {
        const fi = s.u32(l + 4) + slot,
          a = s.access(fi),
          link = s.entry(3, fi);
        if (s.u8(a + 4) === Kind.U32 && s.u32(link + 4) === N)
          offsets.push(s.u32(a));
      }
      offsets.sort((a, b) => a - b);
      if (offsets.length) {
        const terms: string[] = [];
        for (let i = 0; i < offsets.length;) {
          if (
            i + 3 < offsets.length &&
            offsets[i + 3] === offsets[i] + 12 &&
            offsets[i + 1] === offsets[i] + 4 &&
            offsets[i + 2] === offsets[i] + 8
          ) {
            terms.push(`sumU32x4Unchecked(at+${offsets[i]})`);
            i += 4;
          } else terms.push(`<u64>load<u32>(at+${offsets[i++]})`);
        }
        out.push(
          `@inline sumU32Fields(index:u32):u64{if(this.status!=Code.Ok)return 0;if(index>=this.count){this.status=Code.BoundExceeded;return 0;}const at=this.data+this.offset+index*${stride};return ${terms.join("+")};}`,
        );
      }
    }
    if (k === Kind.Record) {
      const li = s.u32(cp + 20),
        l = s.layout(li),
        td = new TypeView(s, s.u32(l + 12));
      for (let slot = 0; slot < s.u32(l + 8); slot++) {
        const fi = s.u32(l + 4) + slot,
          a = s.access(fi),
          ck = s.u8(a + 4),
          link = s.entry(3, fi),
          presence = s.u32(link + 4),
          name = td.field(slot).name(),
          method = "get" + name[0].toUpperCase() + name.slice(1),
          at = `this.offset+index*${stride}+${s.u32(a)}`,
          guard = `if(this.status!=Code.Ok)return ${ck <= 11 ? "0" : "out.status=this.status"};if(index>=this.count){this.status=Code.BoundExceeded;return ${ck <= 11 ? "0" : "out.status=this.status"};}`;
        let presenceGuard = "";
        if (presence !== N) {
          const pr = s.entry(6, presence);
          presenceGuard = `if(!(load<u8>(this.data+this.offset+index*${stride}+${s.u32(pr)})&${s.u8(pr + 4)})){this.status=Code.Absent;return ${ck <= 11 ? "0" : "out.status=this.status"};}`;
        }
        if (ck <= 11)
          out.push(
            `@inline ${method}(index:u32):${types[ck]}{${guard}${presenceGuard}return ${read(ck, `this.data+${at}`, s.u8(a + 6))};}`,
          );
        else if (ck === 12)
          out.push(
            `@inline ${method}BytesInto(index:u32,out:Span):Code{${guard}${presenceGuard}return ${desc(s.plan(s.u32(link)), at, "out")};}`,
          );
        if (ck === 12) {
          const vp = s.plan(s.u32(link));
          if (s.u8(vp + 1) === 4 && s.u8(vp + 2) === 24 && s.u8(vp + 3) === 8)
            out.push(
              `@inline ${method}Span(index:u32):u64{if(this.status!=Code.Ok)return 0;if(index>=this.count){this.status=Code.BoundExceeded;return 0;}${presenceGuard.replace("out.status=this.status", "0")}const word=load<u32>(this.data+${at}),offset=word&0xffffff,count=word>>>24;${s.u32(vp + 16) < 255 ? `if(count>${s.u32(vp + 16)}){this.status=Code.BoundExceeded;return 0;}` : ""}if((count==0)!=(offset==0)||count>this.length||offset>this.length-count){this.status=Code.Malformed;return 0;}return (<u64>count<<32)|<u64>(this.data+offset);}`,
            );
        }
      }
    }
    out.push("}");
  }
  out.push(`export {Layout${s.root} as RootView};`);
  const names = new Set(["Root"]);
  for (let li = 0; li < s.count(1); li++) {
    const l = s.layout(li),
      name = new TypeView(s, s.u32(l + 12)).name();
    if (s.u32(l + 24) !== 1 || names.has(name) || !/^[A-Za-z_]\w*$/.test(name))
      continue;
    names.add(name);
    out.push(`export {Layout${li} as ${name}View};`);
  }
  return out.join("\n") + "\n";
}
